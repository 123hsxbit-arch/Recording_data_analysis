def soc_ocv_method(
    cell_type: int,
    voltage: list[float] | pd.Series | np.ndarray,
    cal_type: str,
    theo_cap: float | None = None,
) -> dict[str, list[float]]:
    """Calculate SOC and capacity by OCV lookup."""
    if cell_type not in OCV_CURVES:
        raise ValueError(f"Unsupported cell type: {cell_type}. Available: {sorted(OCV_CURVES)}")

    if cal_type not in {"ch", "dch"}:
        raise ValueError("cal_type must be 'ch' or 'dch'.")

    if theo_cap is None:
        theo_cap = cell_type + 10

    df_soc = pd.DataFrame(
        {
            "soc": np.arange(0, 101),
            "capacity": np.arange(0, 101) * theo_cap * 0.01,
            "ocv_ch": OCV_CURVES[cell_type]["ch"],
            "ocv_dch": OCV_CURVES[cell_type]["dch"],
        }
    )

    cap_lst: list[float] = []
    soc_lst: list[float] = []
    for value in voltage:
        cap, soc = _lookup_one(df_soc, float(value), cal_type)
        cap_lst.append(cap)
        soc_lst.append(soc)

    return {"cap_lst": cap_lst, "soc_lst": soc_lst}


def _lookup_one(df_soc: pd.DataFrame, value: float, cal_type: str) -> tuple[float, float]:
    if np.isnan(value):
        return np.nan, np.nan

    try:
        if cal_type == "dch":
            temp = df_soc[df_soc["ocv_ch"] >= value]
            ocv_col = "ocv_ch"
            if not temp.empty:
                diff = (temp[ocv_col] * 1000).astype("int") / 1000 - value
                row = temp[diff == diff.min()].iloc[-1]
                return float(row["capacity"]), float(row["soc"])
        else:
            temp = df_soc[df_soc["ocv_dch"] <= value]
            ocv_col = "ocv_dch"
            if not temp.empty:
                diff = value - (temp[ocv_col] * 1000).astype("int") / 1000
                row = temp[diff == diff.min()].iloc[-1]
                return float(row["capacity"]), float(row["soc"])

        ocv_col = "ocv_ch" if cal_type == "dch" else "ocv_dch"
        nearest_index = np.abs(df_soc[ocv_col] - value).idxmin()
        row = df_soc.loc[nearest_index]
        return float(row["capacity"]), float(row["soc"])
    except Exception:
        return np.nan, np.nan
